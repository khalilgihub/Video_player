/**
 * Hybrid Player - YouTube cookie acquisition (one-click).
 *
 * Paths, both writing the same cookies.txt that ytdl_hook consumes:
 *
 * 1. "Sign in to YouTube" (Option A - External Genuine Browser Launch):
 *    Launches the system's installed Google Chrome or Microsoft Edge with a dedicated
 *    profile directory (%APPDATA%\hybrid-player\yt-profile) opening the Google sign-in page.
 *    Because it is the real, Google/Microsoft-signed browser binary, Google BotGuard
 *    passes with 100% compliance and zero warnings. The user signs in normally.
 *    Once the user finishes and closes the browser window, the app briefly starts
 *    that dedicated profile headlessly using Chrome DevTools Protocol (--remote-debugging-port=0),
 *    retrieves the decrypted cookies via Storage.getCookies, writes cookies.txt, and
 *    terminates the headless process.
 *    Chrome's own binary seamlessly handles Windows App-Bound Encryption (v20), and
 *    the dedicated profile prevents Windows EBUSY file-lock conflicts with any currently
 *    running user browser windows.
 * 2. Embedded fallback:
 *    If no Chromium browser is found, falls back to the in-app BrowserWindow.
 * 3. "Import from browser":
 *    Reads cookies from installed Firefox, Chrome, or Edge.
 */

