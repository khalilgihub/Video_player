async function waitForFileAsync(file, timeoutMs = 20000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (fs.existsSync(file)) return true;
    await new Promise((r) => setTimeout(r, 150));
  }
  return false;
}

async function readDevToolsActivePort(portFile, timeoutMs = 20000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (fs.existsSync(portFile)) {
      try {
        const raw = fs.readFileSync(portFile, 'utf8').trim();
        const lines = raw.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
        if (lines.length >= 2 && Number(lines[0]) > 0) {
          const port = lines[0];
          const wsPath = lines[1].startsWith('/') ? lines[1] : `/${lines[1]}`;
          return { port, wsPath };
        }
      } catch (_) {}
    }
    await new Promise((r) => setTimeout(r, 150));
  }
  throw new Error('Chromium debug interface port file not ready in time');
}

function killProcessTree(pid) {
  if (!pid) return;
  if (process.platform === 'win32') {
    try { execSync(`taskkill /pid ${pid} /T /F`, { stdio: 'ignore' }); } catch (_) {}
  } else {
    try { process.kill(-pid, 'SIGKILL'); } catch (_) {
      try { process.kill(pid, 'SIGKILL'); } catch (_) {}
    }
  }
}

function closeProcessGracefully(pid, timeoutMs = 2000) {
  if (!pid) return;
  if (process.platform === 'win32') {
    try {
      execSync(`taskkill /pid ${pid}`, { stdio: 'ignore' });
      const deadline = Date.now() + timeoutMs;
      while (Date.now() < deadline) {
        try {
          process.kill(pid, 0);
          Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
        } catch {
          return;
        }
      }
    } catch (_) {}
    killProcessTree(pid);
  } else {
    try {
      process.kill(pid, 'SIGTERM');
      const deadline = Date.now() + timeoutMs;
      while (Date.now() < deadline) {
        try {
          process.kill(pid, 0);
          Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
        } catch {
          return;
        }
      }
    } catch (_) {}
    killProcessTree(pid);
  }
}

function findChromiumInstall(browser) {
  const isWin = process.platform === 'win32';
  const isMac = process.platform === 'darwin';
  const isLinux = process.platform === 'linux';

  const localAppData = process.env.LOCALAPPDATA || '';
  const progFiles = process.env['PROGRAMFILES'] || 'C:\\Program Files';
  const progFilesX86 = process.env['PROGRAMFILES(X86)'] || 'C:\\Program Files (x86)';

  let files = [];
  if (isWin) {
    files = browser === 'chrome'
      ? [
        path.join(progFiles, 'Google', 'Chrome', 'Application', 'chrome.exe'),
        path.join(progFilesX86, 'Google', 'Chrome', 'Application', 'chrome.exe'),
        path.join(localAppData, 'Google', 'Chrome', 'Application', 'chrome.exe'),
        'C:/Program Files/Google/Chrome/Application/chrome.exe',
        'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
      ]
      : browser === 'edge'
        ? [
          path.join(progFilesX86, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
          path.join(progFiles, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
          path.join(localAppData, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
          'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
          'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
        ]
        : [];
  } else if (isMac) {
    files = browser === 'chrome'
      ? ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome']
      : browser === 'edge'
        ? ['/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge']
        : [];
  } else if (isLinux) {
    files = browser === 'chrome'
      ? ['/usr/bin/google-chrome', '/usr/bin/google-chrome-stable', '/usr/bin/chromium', '/usr/bin/chromium-browser']
      : browser === 'edge'
        ? ['/usr/bin/microsoft-edge', '/usr/bin/microsoft-edge-stable']
        : [];
  }

  const exePath = files.find((p) => { try { return fs.statSync(p).isFile(); } catch { return false; } }) || null;

  const base = isWin
    ? (browser === 'chrome'
      ? path.join(localAppData, 'Google', 'Chrome', 'User Data')
      : browser === 'edge'
        ? path.join(localAppData, 'Microsoft', 'Edge', 'User Data')
        : null)
    : null;
  const profileBase = base && (() => { try { return fs.statSync(base).isDirectory() ? base : null; } catch { return null; } })();

  return { exePath, profileBase };
}

function findInstalledChromiumBrowser() {
  for (const browser of ['chrome', 'edge']) {
    const info = findChromiumInstall(browser);
    if (info && info.exePath) {
      return { browser, exePath: info.exePath };
    }
  }
  return null;
}

function pickChromiumProfileName(profileBase) {
  try {
    const localState = JSON.parse(fs.readFileSync(path.join(profileBase, 'Local State'), 'utf8'));
    const used = localState?.profile?.last_used || localState?.profile?.last_active_profiles?.[0];
    if (used) return used;
  } catch (_) {}
  return 'Default';
}

function cdpCall(port, wsPath, method, params, timeoutMs = 20000) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`CDP timeout: ${method}`)), timeoutMs);
    try {
      if (typeof WebSocket !== 'function') {
        clearTimeout(timer);
        reject(new Error('WebSocket unavailable in main process'));
        return;
      }
      const ws = new WebSocket(`ws://127.0.0.1:${port}${wsPath}`);
      const cleanup = () => { clearTimeout(timer); try { ws.close(); } catch (_) {} };
      ws.addEventListener('open', () => {
        ws.send(JSON.stringify({ id: 1, method, params: params || {} }));
      });
      ws.addEventListener('message', (ev) => {
        try {
          const msg = JSON.parse(typeof ev.data === 'string' ? ev.data : String(ev.data));
          if (msg.id === 1) {
            cleanup();
            if (msg.error) reject(new Error(msg.error.message || 'CDP error'));
            else resolve(msg.result);
          }
        } catch (err) {
          cleanup();
          reject(err);
        }
      });
      ws.addEventListener('close', () => {
        clearTimeout(timer);
        reject(new Error(`CDP connection closed before ${method} responded`));
      });
      ws.addEventListener('error', () => { cleanup(); reject(new Error('CDP connection failed')); });
    } catch (err) {
      clearTimeout(timer);
      reject(err);
    }
  });
}

let activeHeadlessProcess = null;

/**
 * Headlessly extracts YouTube cookies from the dedicated profile directory via CDP.
 */
async function extractCookiesFromDedicatedProfile(browserInfo, dedicatedProfileDir) {
  const portFile = path.join(dedicatedProfileDir, 'DevToolsActivePort');
  try { fs.rmSync(portFile, { force: true }); } catch (_) {}

  const args = [
    `--user-data-dir=${dedicatedProfileDir}`,
    '--headless',
    '--remote-debugging-port=0',
    '--no-first-run',
    '--no-default-browser-check',
    '--disable-background-mode',
    '--disable-features=EdgeStartupBoost',
    '--disable-gpu',
    '--disable-sync',
    '--disable-background-networking',
    '--disable-extensions',
    '--disable-component-update',
    '--window-size=960,720',
    'about:blank',
  ];

  let child = null;
  try {
    child = spawn(browserInfo.exePath, args, { stdio: 'ignore', windowsHide: true });
    activeHeadlessProcess = child;
    ytdbg('headless extraction launched', { browser: browserInfo.browser, pid: child.pid });

    const { port, wsPath } = await readDevToolsActivePort(portFile, 20000);
    const result = await cdpCall(port, wsPath, 'Storage.getCookies', {});
    try {
      await cdpCall(port, wsPath, 'Browser.close', {}, 5000);
    } catch (_) {}
    killProcessTree(child.pid);
    child = null;
    activeHeadlessProcess = null;

    const all = Array.isArray(result?.cookies) ? result.cookies : [];
    const relevant = all
      .filter((c) => isYouTubeRelatedDomain(c.domain))
      .map((c) => ({
        name: c.name,
        value: c.value,
        domain: c.domain,
        hostOnly: !String(c.domain || '').startsWith('.'),
        path: c.path || '/',
        secure: c.secure === true,
        session: c.session === true || !(Number(c.expires) > 0),
        expirationDate: Number(c.expires) > 0 ? Number(c.expires) : undefined,
      }));
    ytdbg('headless extraction read', { browser: browserInfo.browser, total: all.length, relevant: relevant.length });
    return relevant;
  } finally {
    if (child) {
      killProcessTree(child.pid);
      if (activeHeadlessProcess === child) activeHeadlessProcess = null;
    }
    try { fs.rmSync(portFile, { force: true }); } catch (_) {}
    sanitizeProfileWindowPlacement(dedicatedProfileDir);
  }
}

/**
 * Reset crash / abnormal exit flags and remove any collapsed or invalid window
 * placement geometries persisted by headless Chrome, DPI changes, or abnormal terminations.
 */
function sanitizeProfileWindowPlacement(profileDir) {
  if (!profileDir) return;
  try {
    const prefsPath = path.join(profileDir, 'Default', 'Preferences');
    if (fs.existsSync(prefsPath)) {
      const prefs = JSON.parse(fs.readFileSync(prefsPath, 'utf8'));
      let modified = false;
      if (prefs?.profile && prefs.profile.exit_type !== 'Normal') {
        prefs.profile.exit_type = 'Normal';
        modified = true;
      }
      if (prefs?.profile && prefs.profile.exited_cleanly === false) {
        prefs.profile.exited_cleanly = true;
        modified = true;
      }
      // Purge any collapsed window placement saved from previous headless or minimal runs
      if (prefs?.browser) {
        if (prefs.browser.window_placement) { delete prefs.browser.window_placement; modified = true; }
        if (prefs.browser.window_placement_popup) { delete prefs.browser.window_placement_popup; modified = true; }
      }
      if (prefs?.app_window_placement) {
        delete prefs.app_window_placement;
        modified = true;
      }
      if (prefs?.apps?.window_placement) {
        delete prefs.apps.window_placement;
        modified = true;
      }
      if (modified) {
        fs.writeFileSync(prefsPath, JSON.stringify(prefs), 'utf8');
      }
    }
  } catch (_) {}

  try {
    const localStatePath = path.join(profileDir, 'Local State');
    if (fs.existsSync(localStatePath)) {
      const state = JSON.parse(fs.readFileSync(localStatePath, 'utf8'));
      let modified = false;
      if (state?.user_experience_metrics?.stability?.exited_cleanly === false) {
        state.user_experience_metrics.stability.exited_cleanly = true;
        modified = true;
      }
      if (state?.browser) {
        if (state.browser.window_placement) { delete state.browser.window_placement; modified = true; }
        if (state.browser.window_placement_popup) { delete state.browser.window_placement_popup; modified = true; }
      }
      if (modified) {
        fs.writeFileSync(localStatePath, JSON.stringify(state), 'utf8');
      }
    }
  } catch (_) {}
}

