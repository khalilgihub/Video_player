const AUTH_PARTITION = 'persist:youtube-auth';
const COOKIE_HEADER = '# Netscape HTTP Cookie File';
// Straight to the Google sign-in form; after login it continues to
// youtube.com, where the cookie poll picks up the session.
const SIGNIN_URL = 'https://accounts.google.com/ServiceLogin?service=youtube&continue=https%3A%2F%2Fwww.youtube.com%2F&hl=en';
