function setupYouTubeAuthIpc({ getMainWindow, onCookiesChanged } = {}) {
  ipcMain.removeHandler('youtube:open-signin');
  ipcMain.handle('youtube:open-signin', async (event, options = {}) => {
    return openSignInWindow({
      ...options,
      onSuccess: async (result) => {
        ytdbg('sign-in completed', result);
        if (!result?.loggedIn) return;
        const win = typeof getMainWindow === 'function' ? getMainWindow() : null;
        if (win && !win.isDestroyed()) {
          win.webContents.send('youtube:signin-success', { loggedIn: true, count: result?.count || 0 });
        }
        if (typeof onCookiesChanged === 'function') {
          try { onCookiesChanged(); } catch (_) {}
        }
      },
      onBlocked: () => {
        ytdbg('google embedded-browser block page detected');
        const win = typeof getMainWindow === 'function' ? getMainWindow() : null;
        if (win && !win.isDestroyed()) {
          win.webContents.send('youtube:signin-blocked');
        }
      },
    });
  });

  ipcMain.removeHandler('youtube:import-browser-cookies');
  ipcMain.handle('youtube:import-browser-cookies', async () => {
    const result = await importCookiesFromBrowser();
    if (result.success && typeof onCookiesChanged === 'function') {
      try { onCookiesChanged(); } catch (_) {}
    }
    return result;
  });

  ipcMain.removeHandler('youtube:signout');
  ipcMain.handle('youtube:signout', async () => {
    const result = await signOutYouTube();
    if (typeof onCookiesChanged === 'function') {
      try { onCookiesChanged(); } catch (_) {}
    }
    const win = typeof getMainWindow === 'function' ? getMainWindow() : null;
    if (win && !win.isDestroyed()) {
      win.webContents.send('youtube:signout-success');
    }
    return result;
  });

  ipcMain.removeHandler('youtube:account-state');
  ipcMain.handle('youtube:account-state', async () => {
    const state = await getYouTubeSessionState();
    return { loggedIn: state.loggedIn, cookieCount: state.count };
  });
}

/**
 * Signs out / disconnects YouTube session.
 * Removes cookies.txt, clears partition cookies, and dedicated profile cookies.
 */
async function signOutYouTube() {
  ytdbg('signing out of YouTube session');
  isSignInCancelled = true;
  destroySignInWindow();

  const dest = getCookieFilePath();
  let removedFile = false;
  try {
    if (fs.existsSync(dest)) {
      fs.rmSync(dest, { force: true });
      removedFile = true;
    }
  } catch (err) {
    ytdbg('failed to remove cookies.txt on signout', err);
  }

  try {
    if (app && typeof app.isReady === 'function' && app.isReady()) {
      const ses = getAuthSession();
      if (ses) {
        await ses.clearStorageData({
          storages: ['cookies', 'localstorage', 'cachestorage']
        });
      }
    }
  } catch (err) {
    ytdbg('failed to clear partition storage on signout', err);
  }

  try {
    const profileDir = getYoutubeDedicatedProfileDir();
    const candidateFiles = [
      path.join(profileDir, 'Default', 'Network', 'Cookies'),
      path.join(profileDir, 'Default', 'Network', 'Cookies-journal'),
      path.join(profileDir, 'Default', 'Cookies'),
      path.join(profileDir, 'Default', 'Cookies-journal'),
    ];
    for (const file of candidateFiles) {
      if (fs.existsSync(file)) {
        try { fs.rmSync(file, { force: true }); } catch (_) {}
      }
    }
  } catch (_) {}

  return { success: true, removedFile };
}

